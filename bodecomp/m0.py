from __future__ import annotations

import csv
import itertools
from dataclasses import dataclass
from pathlib import Path

from bodecomp.cl import compile_cpp
from bodecomp.coff import Reloc, find_symbol, function_bytes, parse
from bodecomp.xbe import Xbe


@dataclass(frozen=True)
class Candidate:
    address: int
    size: int
    source: Path
    symbol: str


@dataclass(frozen=True)
class Verdict:
    status: str
    detail: str = ""


FLAG_SPELLING = {"SSE": "/arch:SSE"}


def _flag_sets() -> dict[str, tuple[str, ...]]:
    sets = {}
    for opt, frame, cpu, arch in itertools.product(
        ("O1", "O2", "Ox"), ("", "Oy-"), ("", "G6", "G7"), ("", "SSE")
    ):
        parts = [p for p in (opt, frame, cpu, arch) if p]
        sets["-".join(parts)] = tuple(FLAG_SPELLING.get(p, f"/{p}") for p in parts)
    return sets


FLAG_SETS = _flag_sets()


def load_candidates(path: Path) -> list[Candidate]:
    with path.open(newline="") as f:
        return [
            Candidate(
                int(row["address"], 16),
                int(row["size"]),
                Path(row["source"]),
                row["symbol"],
            )
            for row in csv.DictReader(f)
        ]


def compare(target: bytes, built: bytes, relocs: tuple[Reloc, ...]) -> Verdict:
    if relocs:
        names = ", ".join(sorted({r.symbol for r in relocs}))
        return Verdict("has-relocs", f"relocations to {names}")
    extra = built[len(target) :]
    if built[: len(target)] == target and set(extra) <= {0xCC}:
        return Verdict("match")
    first = next(
        (i for i, (a, b) in enumerate(zip(target, built, strict=False)) if a != b),
        min(len(target), len(built)),
    )
    return Verdict(
        "mismatch",
        f"first difference at +0x{first:X}, "
        f"target {len(target)} bytes, built {len(built)} bytes",
    )


def _first_error(log: str) -> str:
    lines = [line.strip() for line in log.splitlines() if line.strip()]
    errors = [line for line in lines if "error" in line.lower()]
    return (errors or lines or [""])[0]


def run_matrix(root, candidates, xbe, flag_sets, compile=compile_cpp):
    results: dict[str, dict[int, Verdict]] = {}
    for name, flags in flag_sets.items():
        row = {}
        for c in candidates:
            output = Path("build/m0") / name / f"{c.address:08x}.obj"
            result = compile(root, c.source, output, flags)
            if not result.ok:
                row[c.address] = Verdict("compile-error", _first_error(result.log))
                continue
            coff = parse((root / output).read_bytes())
            try:
                symbol = find_symbol(coff, c.symbol)
            except LookupError as error:
                row[c.address] = Verdict("symbol-missing", str(error))
                continue
            built, relocs = function_bytes(coff, symbol)
            row[c.address] = compare(xbe.read(c.address, c.size), built, relocs)
        results[name] = row
    return results


def render_report(results, candidates) -> str:
    total = len(candidates)

    def matched(name: str) -> int:
        return sum(v.status == "match" for v in results[name].values())

    ranked = sorted(results, key=matched, reverse=True)
    lines = [
        "# M0 results",
        "",
        "Generated by `uv run python -m bodecomp.m0`.",
        "",
        "| Flags | Matched |",
        "|---|---|",
    ]
    lines += [f"| {name} | {matched(name)}/{total} |" for name in ranked]
    best = ranked[0]
    lines += [
        "",
        f"## Per function under {best}",
        "",
        "| Address | Symbol | Status | Detail |",
        "|---|---|---|---|",
    ]
    for c in candidates:
        verdict = results[best][c.address]
        detail = verdict.detail.replace("|", "/")
        lines.append(
            f"| 0x{c.address:08X} | {c.symbol} | {verdict.status} | {detail} |"
        )
    return "\n".join(lines) + "\n"


DECISION_HEADING = "## Decision"


def write_report(path: Path, report: str) -> None:
    kept = ""
    if path.exists():
        existing = path.read_text()
        start = existing.find(DECISION_HEADING)
        if start != -1:
            kept = "\n" + existing[start:]
    path.write_text(report + kept)


def main() -> None:
    root = Path.cwd()
    candidates = load_candidates(root / "config/m0_candidates.csv")
    xbe = Xbe.parse((root / "orig/default.xbe").read_bytes())
    results = run_matrix(root, candidates, xbe, FLAG_SETS)
    report = render_report(results, candidates)
    write_report(root / "docs/m0-results.md", report)
    print(report)


if __name__ == "__main__":
    main()
